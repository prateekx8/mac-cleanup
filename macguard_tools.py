# ---------------------------------------------------------------- uploads (web UI) and long jobs

MAX_UPLOAD = 200 * 1024 * 1024


def inbox():
    d = os.path.join(mg.STATE_DIR, "tools", "inbox")
    os.makedirs(d, mode=0o700, exist_ok=True)
    os.chmod(d, 0o700)
    return d


def receive(stream, length, name):
    """Save an uploaded file into the private inbox; the caller deletes it after the check."""
    if length <= 0:
        raise ValueError("empty upload")
    if length > MAX_UPLOAD:
        raise ValueError(f"the file is over {MAX_UPLOAD >> 20} MB")
    ext = os.path.splitext(os.path.basename(name or ""))[1].lower()
    ext = ext if ext.isascii() and ext[1:].isalnum() and len(ext) <= 6 else ""
    path = os.path.join(inbox(), uuid.uuid4().hex + ext)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    left = length
    try:
        with os.fdopen(fd, "wb") as fh:
            while left:
                chunk = stream.read(min(left, 1 << 20))
                if not chunk:
                    raise ValueError("the upload stopped early")
                fh.write(chunk)
                left -= len(chunk)
    except BaseException:
        os.remove(path)
        raise
    return path


JOBS = {}
JOBS_LOCK = threading.Lock()


def start_job(name, fn):
    """Run fn(report) in the background; report(done=, total=, note=) updates progress. One job per name."""
    with JOBS_LOCK:
        if JOBS.get(name, {}).get("running"):
            raise ValueError("still busy with the last one")
        JOBS[name] = {"running": True, "done": 0, "total": 0, "note": "", "started": time.time(), "result": None,
                      "error": ""}

    def report(**kw):
        with JOBS_LOCK:
            JOBS[name].update(kw)

    def work():
        try:
            report(result=fn(report))
        except ValueError as e:
            report(error=str(e))
        except Exception as e:  # shown in the UI
            report(error=f"{type(e).__name__}: {e}")
        finally:
            report(running=False)
    threading.Thread(target=work, daemon=True).start()


def job_status(name):
    with JOBS_LOCK:
        return dict(JOBS.get(name) or {"running": False})
