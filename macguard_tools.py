def result(tool, verdict, headline, confidence="none", evidence=None, limits=None, next_steps=None, **extra):
    """The shared result shape (docs/TOOLS.md)."""
    assert verdict in VERDICTS, verdict
    assert confidence in CONFIDENCE, confidence
    return {"tool": tool, "verdict": verdict, "headline": headline, "confidence": confidence,
            "evidence": evidence or [], "limits": limits or [], "next": next_steps or [], **extra}


def helpers():
    """[{name, formula, why, path}] for every optional helper, installed or not."""
    return [{"name": n, "formula": f, "why": why, "path": shutil.which(n) or ""} for n, f, why in HELPERS]


