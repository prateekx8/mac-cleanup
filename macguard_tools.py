"""The Tools section: one-off utilities that run on this Mac (docs/TOOLS.md).

Every tool returns the same result shape, so the CLI, the web UI, the app and MCP show them alike.
Tool modules (macguard_recover.py, later macguard_aicheck.py and macguard_photos.py) are loaded only when used.
"""
import os
import shutil

import macguard as mg

TOOLS = [
    {"id": "recover", "name": "Recover files", "status": "ready",
     "what": "Get back deleted files: Trash, Time Machine, local snapshots, git, editor history; check a memory card",
     "gives": "nothing, or a memory card / USB stick", "cli": "macguard recover", "doc": "docs/RECOVERY.md"},
    {"id": "ai-image", "name": "AI image check", "status": "planned",
     "what": "Was this picture made or edited by AI? With the evidence and how strong it is",
     "gives": "a photo or picture (JPEG, PNG, HEIC, WebP)", "cli": "macguard ai-check FILE", "doc": "docs/AI-DETECTION.md"},
    {"id": "ai-voice", "name": "AI voice check", "status": "planned",
     "what": "Was this voice generated by AI? With the evidence and how strong it is",
     "gives": "an audio or voice clip (WAV, MP3, M4A, AAC)", "cli": "macguard ai-check FILE", "doc": "docs/AI-DETECTION.md"},
    {"id": "photo-sort", "name": "Photo sorter", "status": "planned",
     "what": "Index a folder of photos (dates, camera, what Apple Vision sees), then sort them by event, month or kind",
     "gives": "a folder of photos, a memory card or a backup drive", "cli": "macguard photos", "doc": "docs/PHOTO-SORT.md"},
]

# Outside programs that make tools better when installed. Never installed by macguard itself.
HELPERS = [
    ("photorec", "testdisk", "deep recovery of memory cards (PhotoRec)"),
    ("ddrescue", "ddrescue", "copying a failing card safely"),
    ("tsk_recover", "sleuthkit", "undelete with file names (The Sleuth Kit)"),
    ("c2patool", "c2patool", "verifying Content Credentials signatures"),
    ("exiftool", "exiftool", "reading every kind of photo metadata"),
]

VERDICTS = ("found", "nothing-found", "ai-proven", "ai-declared", "ai-edited", "likely-ai", "no-markers",
            "unsupported", "info")
CONFIDENCE = ("proven", "strong", "moderate", "weak", "none")


def result(tool, verdict, headline, confidence="none", evidence=None, limits=None, next_steps=None, **extra):
    """The shared result shape (docs/TOOLS.md)."""
    assert verdict in VERDICTS, verdict
    assert confidence in CONFIDENCE, confidence
    return {"tool": tool, "verdict": verdict, "headline": headline, "confidence": confidence,
            "evidence": evidence or [], "limits": limits or [], "next": next_steps or [], **extra}


def helpers():
    """[{name, formula, why, path}] for every optional helper, installed or not."""
    return [{"name": n, "formula": f, "why": why, "path": shutil.which(n) or ""} for n, f, why in HELPERS]


def home_short(path):
    return path.replace(mg.HOME, "~", 1) if path and path.startswith(mg.HOME) else path


def cmd_tools(args):
    print(f"{mg.C['B']}Tools{mg.C['x']} {mg.C['d']}(everything runs on this Mac){mg.C['x']}")
    for t in TOOLS:
        tag = f"{mg.C['g']}ready{mg.C['x']}  " if t["status"] == "ready" else f"{mg.C['d']}planned{mg.C['x']}"
        print(f"  {tag} {mg.C['B']}{t['name']:<16}{mg.C['x']} {t['what']}")
        print(f"          {mg.C['d']}give it: {t['gives']} · {t['cli']} · {t['doc']}{mg.C['x']}")
    print(f"\n{mg.C['B']}Optional helpers{mg.C['x']} {mg.C['d']}(used when installed; never installed for you){mg.C['x']}")
    for h in helpers():
        mark = f"{mg.C['g']}✔{mg.C['x']}" if h["path"] else f"{mg.C['d']}–{mg.C['x']}"
        print(f"  {mark} {h['name']:<12} {mg.C['d']}{h['why']}"
              f"{'' if h['path'] else ' · brew install ' + h['formula']}{mg.C['x']}")
